const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  console.log("--------------------------------------------------");
  console.log("Starting deployment of FileStorage smart contract...");
  console.log("--------------------------------------------------");

  const [deployer] = await hre.ethers.getSigners();
  console.log("Deploying contract with account:", deployer.address);

  const balance = await hre.ethers.provider.getBalance(deployer.address);
  console.log("Account balance:", hre.ethers.formatEther(balance), "ETH");

  const FileStorage = await hre.ethers.getContractFactory("FileStorage");
  const fileStorage = await FileStorage.deploy();
  await fileStorage.waitForDeployment();

  const contractAddress = await fileStorage.getAddress();
  console.log("==================================================");
  console.log(" FileStorage DEPLOYED SUCCESSFULLY!");
  console.log(" CONTRACT ADDRESS:", contractAddress);
  console.log("==================================================");

  // Sync address & ABI to frontend/src/contracts
  const frontendContractsDir = path.join(__dirname, "../../frontend/src/contracts");
  if (!fs.existsSync(frontendContractsDir)) {
    fs.mkdirSync(frontendContractsDir, { recursive: true });
  }

  // Get contract artifact for ABI
  const artifactPath = path.join(
    __dirname,
    "../artifacts/contracts/FileStorage.sol/FileStorage.json"
  );

  if (fs.existsSync(artifactPath)) {
    const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
    const abiFilePath = path.join(frontendContractsDir, "FileStorageABI.json");
    fs.writeFileSync(abiFilePath, JSON.stringify(artifact.abi, null, 2));
    console.log(" Saved ABI to:", abiFilePath);
  }

  // Write contractConfig.js
  const configContent = `// Auto-generated by deploy script
export const CONTRACT_ADDRESS = "${contractAddress}";
export const RPC_URL = "http://127.0.0.1:8545";
export const CHAIN_ID = 31337;
`;
  const configFilePath = path.join(frontendContractsDir, "contractConfig.js");
  fs.writeFileSync(configFilePath, configContent);
  console.log(" Saved contract config to:", configFilePath);

  // Update root .env if it exists
  const rootEnvPath = path.join(__dirname, "../../.env");
  if (fs.existsSync(rootEnvPath)) {
    let envContent = fs.readFileSync(rootEnvPath, "utf8");
    envContent = envContent.replace(
      /CONTRACT_ADDRESS=.*/g,
      `CONTRACT_ADDRESS=${contractAddress}`
    );
    envContent = envContent.replace(
      /VITE_CONTRACT_ADDRESS=.*/g,
      `VITE_CONTRACT_ADDRESS=${contractAddress}`
    );
    fs.writeFileSync(rootEnvPath, envContent);
    console.log(" Updated CONTRACT_ADDRESS in root .env file");
  }

  console.log("Deployment and synchronization complete!");
}

main().catch((error) => {
  console.error("Deployment failed:", error);
  process.exitCode = 1;
});
